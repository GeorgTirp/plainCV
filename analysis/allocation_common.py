MAIN_BODY_OPTIMIZERS = ("sgd", "signum", "adam", "muon", "soap")
CONTROL_OPTIMIZERS = ("hadamard-signum", "kaon")


def canonical_optimizer(name: str) -> str:
    """One spelling per optimizer across architectures.

    The LM arm directory is ``GGN_hadamard-signum_seeds`` while the ViT one is
    ``GGN_vit_tinyimagenet_hadamard_signum_seeds``; without normalizing, the two
    architectures would report two different optimizers.
    """
    return name.strip().lower().replace("_", "-")


def optimizer_family(name: str) -> str:
    """``main`` for the five main-body arms, ``control`` for the ablations."""
    return "main" if canonical_optimizer(name) in MAIN_BODY_OPTIMIZERS else "control"


def discover_eigen_runs(family: str = "lm", root: Optional[str] = None) -> list:
    """Every run under the paper-runs tree that has ``eigen_tracking.csv``.

    Mirrors :func:`discover_runs`, but the Section-1 CSVs are optional: ``tags``
    is left empty when they are absent, which is the normal state on ViT.
    """
    root = root or (LM_RUNS if family == "lm" else VIT_RUNS)
    runs: list = []
    if not os.path.isdir(root):
        return runs
    for arm in sorted(os.listdir(root)):
        arm_dir = os.path.join(root, arm)
        if not os.path.isdir(arm_dir):
            continue
        m = re.match(r"GGN_(?:vit_tinyimagenet_)?(.+?)_seeds$", arm)
        optimizer = m.group(1) if m else arm
        for job in sorted(os.listdir(arm_dir)):
            job_dir = os.path.join(arm_dir, job)
            eig = os.path.join(job_dir, "eigen_tracking.csv")
            if not os.path.isfile(eig):
                continue
            tags_path = os.path.join(job_dir, "section1_block_tags.csv")
            jm = re.match(r"job_idx_(\d+)$", job)
            job_idx = int(jm.group(1)) if jm else -1
            runs.append(
                Run(
                    family=family,
                    optimizer=canonical_optimizer(optimizer),
                    seed=JOB_IDX_TO_SEED.get(job_idx, job_idx),
                    job_idx=job_idx,
                    path=job_dir,
                    measures=pd.read_csv(eig),
                    tags=(
                        pd.read_csv(tags_path)
                        if os.path.isfile(tags_path)
                        else pd.DataFrame()
                    ),
                )
            )
    return runs


def eigen_panel(
    runs: list,
    tol: float = STEP_TOL_DEFAULT,
    drop_lone_arms: bool = True,
    align_seeds: bool = True,
) -> tuple:
    """Stack every run's eigen-tracking rows onto one shared checkpoint grid.

    Returns ``(panel, info)``. ``panel`` carries the raw CSV columns with
    ``arm, architecture, family, optimizer, seed, matched_step`` prepended;
    ``info`` records what the two filters removed, for the caller to print.

    Three things happen here that every Section-3 script needs identically:

    * **Clustering.** SOAP is measured on its own grid (LM ``34 + 576k`` against
      the other arms' ``576k``; ViT ``27 + 575k`` against ``576k``, so the offset
      there drifts from +27 to -27 across training). Rows are keyed on
      :func:`checkpoint_map`'s shared label, and the realised cluster diameter is
      checked against ``2 * tol`` -- single linkage can chain two clusters into
      one once more grids enter the pool, and that must fail loudly rather than
      quietly averaging two measurement occasions together.
    * **Lone-arm labels.** SOAP's transient first probe (LM 34, ViT 27) has no
      counterpart in any other arm, so it is dropped rather than compared
      against nothing.
    * **Seed alignment.** LM Kaon stops at 9216 on two seeds and 9792 on the
      third. Intersecting each arm's grid across its seeds keeps the late-half
      window over the same steps for every seed, matching what
      ``compute_paper_quantities.align_seeds`` does.
    """
    step_map = checkpoint_map(runs, tol)
    frames = []
    for run in runs:
        df = run.measures.copy()
        df.insert(0, "matched_step", [
            matched_step_of(step_map, s) for s in df["global_step"]
        ])
        df.insert(0, "seed", run.seed)
        df.insert(0, "optimizer", run.optimizer)
        df.insert(0, "family", optimizer_family(run.optimizer))
        df.insert(0, "architecture", run.family)
        df.insert(0, "arm", os.path.basename(os.path.dirname(run.path)))
        frames.append(df)
    if not frames:
        return pd.DataFrame(), {}
    panel = pd.concat(frames, ignore_index=True)

    span = panel.groupby("matched_step")["global_step"].agg(lambda s: s.max() - s.min())
    worst = int(span.max()) if len(span) else 0
    if worst > 2 * tol:
        offenders = span[span > 2 * tol]
        raise SystemExit(
            f"checkpoint clustering failed: cluster diameter {worst} exceeds "
            f"2*tol = {2 * tol:g} at matched_step(s) "
            f"{sorted(int(s) for s in offenders.index)}. Single linkage has "
            f"chained separate measurement occasions together; lower --step-tol."
        )

    info = {
        "n_runs": len(runs),
        "step_tol": float(tol),
        "max_cluster_diameter": worst,
        "n_labels": int(panel["matched_step"].nunique()),
        "dropped_lone_arm": [],
        "dropped_seed_align": 0,
    }

    if drop_lone_arms:
        per_label = panel.groupby("matched_step")["optimizer"].nunique()
        lone = sorted(int(s) for s in per_label[per_label < 2].index)
        if lone:
            info["dropped_lone_arm"] = lone
            panel = panel[~panel["matched_step"].isin(lone)].reset_index(drop=True)

    if align_seeds:
        keep = []
        for _, sub in panel.groupby(["architecture", "optimizer"], sort=False):
            n_seeds = sub["seed"].nunique()
            counts = sub.groupby("matched_step")["seed"].nunique()
            shared = counts[counts == n_seeds].index
            keep.append(sub[sub["matched_step"].isin(shared)])
        aligned = pd.concat(keep, ignore_index=True) if keep else panel
        info["dropped_seed_align"] = int(len(panel) - len(aligned))
        panel = aligned

    info["n_rows"] = int(len(panel))
    return panel, info


# Columns E and F both derive. Kept in one place so the two scripts cannot end
# up with different guard sets or a different sign convention.
EOS_GUARD_COLS = ("grad_norm", "update_norm", "full_update_grad_cosine")


def eos_frame(panel: pd.DataFrame) -> pd.DataFrame:
    """Add the EoS coordinate and the Eq.(6) channels to an eigen panel.

    Two logged conventions matter and are *not* re-applied here:

    * ``full_update_grad_cosine`` is already sign-flipped at logging time, so a
      descent step has ``cos > 0``. It is used as logged.
    * ``ritz_resid_*`` is already relative (residual over eigenvalue). G reads it
      as logged; nothing in this module renormalizes it.

    ``guard_ok`` marks the rows on which the coordinate is defined
    (``gnorm > 0``, ``unorm > 0``, ``cos > 0``). Rows with ``cos <= 0`` are
    ascent steps in the first-order sense; they are flagged, never silently
    dropped, so the caller can count and report them.
    """
    df = panel.copy()
    A = df["actual_update_rayleigh"].astype(float)
    gnorm = df["grad_norm"].astype(float)
    unorm = df["update_norm"].astype(float)
    cos = df["full_update_grad_cosine"].astype(float)
    lmax = df["eig_0"].astype(float)

    df["A"] = A
    df["gnorm"] = gnorm
    df["unorm"] = unorm
    df["cos"] = cos
    df["lmax"] = lmax

    finite = np.isfinite(A) & np.isfinite(gnorm) & np.isfinite(unorm) & np.isfinite(cos)
    df["guard_ok"] = finite & (gnorm > 0) & (unorm > 0) & (cos > 0)
    df["ascent_step"] = finite & (cos <= 0)

    ok = df["guard_ok"].to_numpy()
    nan = np.full(len(df), np.nan)

    # -g'Delta: the first-order gain per unit step, positive on a descent step.
    gdotd = np.where(ok, gnorm * unorm * cos, nan)
    eta_eff = np.where(ok, unorm**2 / gdotd, nan)

    df["gdotd"] = gdotd
    df["eta_eff"] = eta_eff
    df["rho_dir"] = eta_eff * A
    df["rho_max"] = eta_eff * lmax          # counterfactual, not a trajectory property
    df["A_over_lmax"] = np.where(lmax > 0, A / lmax, nan)
    df["efficiency"] = 1.0 - df["rho_dir"] / 2.0

    # Eq. (6) channels. ``scale`` drops the 1/2: a constant factor shifts no log
    # spread and no rank correlation.
    df["scale"] = np.where(lmax > 0, gnorm**2 / lmax, nan)
    df["align"] = cos**2
    df["exposure"] = df["A_over_lmax"]
    df["Phi_model"] = df["scale"] * df["align"] / df["exposure"]
    return df


def probe_reduction(df: pd.DataFrame) -> np.ndarray:
    """``probe_loss_reduction``, or the relative before/after drop if absent."""
    if "probe_loss_reduction" in df.columns:
        return df["probe_loss_reduction"].to_numpy(dtype=float)
    before = df["probe_loss_before"].to_numpy(dtype=float)
    after = df["probe_loss_after"].to_numpy(dtype=float)
    return np.where(before > 0, (before - after) / before, np.nan)


def log_sd(values) -> float:
    """Population sd of the natural log, NaN unless >= 2 positive finite values."""
    v = np.asarray(values, dtype=float)
    v = v[np.isfinite(v) & (v > 0)]
    if v.size < 2:
        return float("nan")
    return float(np.std(np.log(v), ddof=0))


def max_over_min(values) -> float:
    """Spread as a plain ratio, NaN unless every value is positive and finite."""
    v = np.asarray(values, dtype=float)
    v = v[np.isfinite(v) & (v > 0)]
    if v.size < 2:
        return float("nan")
    return float(v.max() / v.min())


def window_frame(df: pd.DataFrame, window: str) -> pd.DataFrame:
    """``all`` or the late half of each (architecture, optimizer, seed) run."""
    if window == "all":
        return df
    if window == "late":
        return late_half(df, group_cols=["architecture", "optimizer", "seed"])
    raise ValueError(f"unknown window {window!r}")
