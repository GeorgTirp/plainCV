"""Shared loading + allocation-gain math for the Section-C analyses (C1-C5).

The object of study is how an optimizer *places* its update energy across the
87 contiguous parameter blocks, scored against the placement that would maximise
the first-order gain at the same checkpoint.

For an allocation ``w`` over blocks (``w_b >= 0``, ``sum_b w_b = 1``), with
per-block first-order gain coefficient ``beta_b`` and per-block curvature
exposure ``A_b``:

    G(w)  = (sum_b sqrt(w_b) beta_b)^2 / sum_b w_b (A_b + delta)     gain
    G*    = sum_b beta_b^2 / (A_b + delta)                           optimal gain
    R     = G(w) / G*                                                in [0, 1]
    w*_b  proportional to (beta_b / (A_b + delta))^2                 optimum
    cert(w) = sum_b w_b AM_b / AM                                    block certificate

``delta`` is a damping set as a fraction of the block-diagonal exposure
``sum_b w_b A_b``; it keeps ``G*`` finite when some block has ``A_b -> 0``.

Two ``beta`` channels are supported:
  * ``proxy``    -- ``beta_b^2 = size_b * AM_b`` (no gradient logging needed)
  * ``measured`` -- ``beta_b^2 = block_gnorm2_b * block_cos_b^2`` (needs the A1/A2
    columns from ``section1_measures``)
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from typing import Optional

import numpy as np
import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LM_RUNS = os.path.join(REPO, "exp", "paper_runs", "llm")
VIT_RUNS = os.path.join(REPO, "exp", "paper_runs", "vit")

# job_idx -> seed, as generated by run_all_seeds.sh (SEED_LIST order).
JOB_IDX_TO_SEED = {0: 0, 1: 42, 2: 137}

W_FLOOR = 1e-12
DELTA_FRAC_DEFAULT = 1e-3

# Arms are not measured on the same step grid. SOAP runs with
# eigen_tracking_post_soap_refresh, so its first probe lands at
# precondition_frequency + 2 = 34 and every later checkpoint is offset by the
# same +34: 610, 1186, ..., 9250, ..., 12130 against the other arms' 576, 1152,
# ..., 9216, ..., 12672. Matching arms on exact global_step therefore drops SOAP
# from every cross-arm view. Checkpoints within STEP_TOL of each other are the
# same measurement occasion and are clustered onto one label.
STEP_TOL_DEFAULT = 64


@dataclass
class Run:
    """One training run's Section-1 measures plus its static block tags."""

    family: str          # "lm" | "vit"
    optimizer: str
    seed: int
    job_idx: int
    path: str
    measures: pd.DataFrame
    tags: pd.DataFrame

    @property
    def n_blocks(self) -> int:
        return len(self.tags)

    @property
    def namesake(self) -> np.ndarray:
        return self.tags["namesake"].to_numpy().astype(bool)

    @property
    def sizes(self) -> np.ndarray:
        return self.tags["size"].to_numpy().astype(np.float64)

    @property
    def label(self) -> str:
        return f"{self.family}/{self.optimizer}/s{self.seed}"


def _block_array(df_row: pd.Series, prefix: str, n_blocks: int) -> np.ndarray:
    """Pull ``prefix_0 .. prefix_{n-1}`` out of one CSV row as a float array."""
    cols = [f"{prefix}_{b}" for b in range(n_blocks)]
    missing = [c for c in cols if c not in df_row.index]
    if missing:
        return np.full(n_blocks, np.nan)
    return df_row[cols].to_numpy(dtype=np.float64)


def has_columns(run: Run, prefix: str) -> bool:
    return f"{prefix}_0" in run.measures.columns


def discover_runs(family: str = "lm", root: Optional[str] = None) -> list:
    """Find every run under the paper-runs tree that has Section-1 measures."""
    root = root or (LM_RUNS if family == "lm" else VIT_RUNS)
    runs: list = []
    if not os.path.isdir(root):
        return runs
    for arm in sorted(os.listdir(root)):
        arm_dir = os.path.join(root, arm)
        if not os.path.isdir(arm_dir):
            continue
        m = re.match(r"GGN_(?:vit_tinyimagenet_)?(.+?)_seeds$", arm)
        optimizer = m.group(1) if m else arm
        for job in sorted(os.listdir(arm_dir)):
            job_dir = os.path.join(arm_dir, job)
            meas = os.path.join(job_dir, "section1_measures.csv")
            tags = os.path.join(job_dir, "section1_block_tags.csv")
            if not (os.path.isfile(meas) and os.path.isfile(tags)):
                continue
            jm = re.match(r"job_idx_(\d+)$", job)
            job_idx = int(jm.group(1)) if jm else -1
            runs.append(
                Run(
                    family=family,
                    optimizer=optimizer,
                    seed=JOB_IDX_TO_SEED.get(job_idx, job_idx),
                    job_idx=job_idx,
                    path=job_dir,
                    measures=pd.read_csv(meas),
                    tags=pd.read_csv(tags),
                )
            )
    return runs


@dataclass
class Checkpoint:
    """One measurement row reduced to the blocks that carry a defined gain."""

    run: Run
    global_step: int
    valid: np.ndarray     # bool mask over all blocks
    w: np.ndarray         # allocation over valid blocks, renormalized to sum 1
    A: np.ndarray         # block Rayleigh exposure A_b
    AM: np.ndarray        # block arithmetic-mean curvature AM_b
    beta2: np.ndarray     # squared first-order gain coefficient
    size: np.ndarray
    namesake: np.ndarray
    AM_full: float        # full-space AM reference for the certificate
    channel: str

    @property
    def n(self) -> int:
        return int(self.w.size)


def build_checkpoint(
    run: Run,
    row: pd.Series,
    channel: str = "proxy",
) -> Optional[Checkpoint]:
    """Reduce one measurement row to a Checkpoint, or None if unusable.

    Blocks are kept when ``w_b > 1e-12``, ``A_b > 0`` and ``AM_b > 0``; the
    surviving ``w`` is renormalized so it remains a probability vector.
    """
    n = run.n_blocks
    w_raw = _block_array(row, "block_w", n)
    A = _block_array(row, "block_A", n)
    AM = _block_array(row, "block_AM", n)

    if channel == "proxy":
        beta2 = run.sizes * AM
    elif channel == "measured":
        gn2 = _block_array(row, "block_gnorm2", n)
        cos = _block_array(row, "block_cos", n)
        beta2 = gn2 * np.square(cos)
    else:
        raise ValueError(f"unknown beta channel {channel!r}")

    valid = (
        np.isfinite(w_raw) & (w_raw > W_FLOOR)
        & np.isfinite(A) & (A > 0)
        & np.isfinite(AM) & (AM > 0)
        & np.isfinite(beta2) & (beta2 >= 0)
    )
    if valid.sum() < 2:
        return None

    w = w_raw[valid]
    w = w / w.sum()
    return Checkpoint(
        run=run,
        global_step=int(row["global_step"]),
        valid=valid,
        w=w,
        A=A[valid],
        AM=AM[valid],
        beta2=beta2[valid],
        size=run.sizes[valid],
        namesake=run.namesake[valid],
        AM_full=float(row["AM"]),
        channel=channel,
    )


def damping(ck: Checkpoint, frac: float = DELTA_FRAC_DEFAULT) -> float:
    """delta = frac * (block-diagonal exposure sum_b w_b A_b) over valid blocks."""
    return float(frac) * float(np.sum(ck.w * ck.A))


def gain(w: np.ndarray, beta2: np.ndarray, A: np.ndarray, delta: float) -> float:
    """G(w) = (sum_b sqrt(w_b) beta_b)^2 / sum_b w_b (A_b + delta)."""
    num = np.square(np.sum(np.sqrt(np.maximum(w, 0.0) * beta2)))
    den = np.sum(w * (A + delta))
    return float(num / den) if den > 0 else float("nan")


def optimal_gain(beta2: np.ndarray, A: np.ndarray, delta: float) -> float:
    """G* = sum_b beta_b^2 / (A_b + delta)."""
    return float(np.sum(beta2 / (A + delta)))


def optimal_w(beta2: np.ndarray, A: np.ndarray, delta: float) -> np.ndarray:
    """w*_b proportional to (beta_b / (A_b + delta))^2, normalized to sum 1."""
    unnorm = beta2 / np.square(A + delta)
    total = unnorm.sum()
    if not np.isfinite(total) or total <= 0:
        return np.full_like(unnorm, np.nan)
    return unnorm / total


def certificate(w: np.ndarray, AM: np.ndarray, AM_full: float) -> float:
    """cert(w) = sum_b w_b AM_b / AM (block-level, GD-rung reference)."""
    if not np.isfinite(AM_full) or AM_full <= 0:
        return float("nan")
    return float(np.sum(w * AM) / AM_full)


def spearman(x: np.ndarray, y: np.ndarray) -> float:
    """Spearman rank correlation, NaN-safe, NaN when it is not defined."""
    ok = np.isfinite(x) & np.isfinite(y)
    if ok.sum() < 3:
        return float("nan")
    from scipy.stats import spearmanr

    rho = spearmanr(x[ok], y[ok]).statistic
    return float(rho) if np.isfinite(rho) else float("nan")


def score_allocation(
    ck: Checkpoint,
    w: Optional[np.ndarray] = None,
    delta_frac: float = DELTA_FRAC_DEFAULT,
) -> dict:
    """R, cert, namesake share and w-vs-w* Spearman for one allocation."""
    w = ck.w if w is None else w
    delta = damping(ck, delta_frac)
    G = gain(w, ck.beta2, ck.A, delta)
    Gstar = optimal_gain(ck.beta2, ck.A, delta)
    wstar = optimal_w(ck.beta2, ck.A, delta)
    return {
        "R": float(G / Gstar) if Gstar > 0 else float("nan"),
        "G": G,
        "G_star": Gstar,
        "cert": certificate(w, ck.AM, ck.AM_full),
        "namesake_share": float(np.sum(w[ck.namesake])),
        "spearman_w_wstar": spearman(w, wstar),
        "delta": delta,
        "n_blocks_valid": ck.n,
    }


def rescale_fallback(ck: Checkpoint, rho: float) -> np.ndarray:
    """Multiply fallback-block *energies* by rho^2 and renormalize (C2).

    Directions are held fixed: beta_b and A_b are the measured ones, only the
    energy split between namesake and fallback blocks moves. This is an
    instantaneous, same-checkpoint counterfactual -- it does not model how
    training would have evolved under a different fallback ratio.
    """
    w = ck.w.copy()
    w[~ck.namesake] *= float(rho) ** 2
    total = w.sum()
    return w / total if total > 0 else np.full_like(w, np.nan)


def rho_for_namesake_share(ck: Checkpoint, target: float = 0.5) -> float:
    """rho making the namesake energy share equal ``target`` after rescaling."""
    s_ns = float(np.sum(ck.w[ck.namesake]))
    s_fb = float(np.sum(ck.w[~ck.namesake]))
    if s_fb <= 0 or s_ns <= 0 or not (0.0 < target < 1.0):
        return float("nan")
    # s_ns / (s_ns + rho^2 s_fb) = target
    return float(np.sqrt((s_ns * (1.0 - target)) / (target * s_fb)))


def namesake_only(ck: Checkpoint) -> Optional[tuple]:
    """Restrict to namesake blocks, renormalizing w over them (C2)."""
    m = ck.namesake
    if m.sum() < 2 or ck.w[m].sum() <= 0:
        return None
    sub = Checkpoint(
        run=ck.run,
        global_step=ck.global_step,
        valid=ck.valid,
        w=ck.w[m] / ck.w[m].sum(),
        A=ck.A[m],
        AM=ck.AM[m],
        beta2=ck.beta2[m],
        size=ck.size[m],
        namesake=ck.namesake[m],
        AM_full=ck.AM_full,
        channel=ck.channel,
    )
    return (sub,)


def checkpoint_map(runs: list, tol: float = STEP_TOL_DEFAULT) -> dict:
    """Map each run's ``global_step`` onto a shared checkpoint label.

    Single-linkage clustering over the pooled steps: consecutive steps closer
    than ``tol`` belong to the same measurement occasion. Each cluster is
    labelled by its smallest member, so the majority arms keep their own grid
    (576, 1152, ...) and SOAP's +34 offset folds into it. A step with no
    neighbour within ``tol`` -- SOAP's transient first probe at 34 -- forms its
    own cluster and simply has no counterpart in the other arms.
    """
    steps = np.unique(
        np.concatenate(
            [r.measures["global_step"].to_numpy(dtype=np.int64) for r in runs]
        )
    )
    if steps.size == 0:
        return {}
    breaks = np.where(np.diff(steps) > tol)[0]
    mapping = {}
    for group in np.split(steps, breaks + 1):
        label = int(group.min())
        for s in group:
            mapping[int(s)] = label
    return mapping


def matched_step_of(mapping: dict, step: int) -> int:
    """Shared checkpoint label for ``step`` (identity when unmapped)."""
    return int(mapping.get(int(step), int(step)))


def iter_checkpoints(runs: list, channel: str = "proxy"):
    """Yield (run, Checkpoint) for every measurement row of every run."""
    for run in runs:
        for _, row in run.measures.iterrows():
            ck = build_checkpoint(run, row, channel=channel)
            if ck is not None:
                yield run, ck


def late_half(
    df: pd.DataFrame,
    step_col: str = "matched_step",
    group_cols: Optional[list] = None,
) -> pd.DataFrame:
    """Second half of the checkpoints of each trajectory.

    Matches compute_paper_quantities' late-training window, which is where the
    paper's headline numbers are read off; the early checkpoints sit in a
    different training phase and pull the run-averaged values down.

    ``group_cols`` defaults to (optimizer, seed); pass a longer list when the
    frame stacks several settings, so the halving happens within each one.
    """
    group_cols = group_cols or ["optimizer", "seed"]
    group_cols = [c for c in group_cols if c in df.columns]
    if not group_cols or df.empty:
        return df
    keep = []
    for _, sub in df.groupby(group_cols, sort=False):
        sub = sub.sort_values(step_col)
        keep.append(sub.iloc[len(sub) // 2:])
    return pd.concat(keep, ignore_index=True) if keep else df


def seed_summary(df: pd.DataFrame, group_cols: list, value_cols: list) -> pd.DataFrame:
    """Mean +/- sd across seeds, after averaging within each seed."""
    per_seed = df.groupby(group_cols + ["seed"], as_index=False)[value_cols].mean()
    agg = per_seed.groupby(group_cols, as_index=False).agg(
        {**{c: ["mean", "std", "count"] for c in value_cols}}
    )
    agg.columns = group_cols + [
        f"{c}_{stat}" for c in value_cols for stat in ("mean", "sd", "n")
    ]
    return agg


